"""orbit_search.py -- the search that found the n = 67 example (needs OR-Tools: pip install ortools).

For v = 2n - 1 and a subgroup H of the units of Z_v, take A and B to be unions of H-orbits of Z_v,
with A = -A, 0 not in A and |A| = |B| = n - 1. One 0/1 variable per orbit turns the inequality

    (*)   N_AA(d) + N_BB(d) <= n - 1 - [d in A]       for every d != 0

of Proposition 2.3 into quadratic constraints, one per H-orbit of d (the left side is constant on
H-orbits). CP-SAT solves the system; a solution is checked again from scratch on all pairs of
vertices of the graph and written as JSON.

Usage:
  python3 search/orbit_search.py                 n = 67, H = cube roots of unity mod 133
  python3 search/orbit_search.py 67 11 30        n = 67, H generated by 11 and 30
  options: --time SECONDS (default 60), --workers K (default 4), --seed S, --out FILE
"""
import argparse
import json
import sys

from ortools.sat.python import cp_model


def subgroup(v, gens):
    H, todo = {1}, [1]
    while todo:
        x = todo.pop()
        for g in gens:
            y = x * g % v
            if y not in H:
                H.add(y)
                todo.append(y)
    return sorted(H)


def search(n, H, time_limit, workers, seed):
    v = 2 * n - 1
    orbit_of, orbits = {}, []
    for x in range(v):
        if x not in orbit_of:
            O = sorted({h * x % v for h in H})
            for y in O:
                orbit_of[y] = len(orbits)
            orbits.append(O)
    k = len(orbits)
    m = cp_model.CpModel()
    a = [m.NewBoolVar(f"a{i}") for i in range(k)]
    b = [m.NewBoolVar(f"b{i}") for i in range(k)]
    m.Add(a[orbit_of[0]] == 0)
    for i, O in enumerate(orbits):
        m.Add(a[i] == a[orbit_of[(-O[0]) % v]])                 # A = -A
    m.Add(sum(len(O) * a[i] for i, O in enumerate(orbits)) == n - 1)
    m.Add(sum(len(O) * b[i] for i, O in enumerate(orbits)) == n - 1)
    prod = {}

    def both(x, i, j):                                         # x[i] and x[j]
        if i == j:
            return x[i]
        key = (id(x), min(i, j), max(i, j))
        if key not in prod:
            p = m.NewBoolVar("p")
            m.AddMultiplicationEquality(p, [x[i], x[j]])
            prod[key] = p
        return prod[key]

    for i, O in enumerate(orbits):
        d = O[0]
        if d == 0:
            continue
        lhs = [both(x, orbit_of[y], orbit_of[(y + d) % v]) for x in (a, b) for y in range(v)]
        m.Add(sum(lhs) <= n - 1 - a[i])
    solver = cp_model.CpSolver()
    solver.parameters.max_time_in_seconds = time_limit
    solver.parameters.num_workers = workers
    solver.parameters.random_seed = seed
    st = solver.Solve(m)
    if st not in (cp_model.OPTIMAL, cp_model.FEASIBLE):
        return solver.StatusName(st), None, None, k
    A = sorted(y for i, O in enumerate(orbits) if solver.Value(a[i]) for y in O)
    B = sorted(y for i, O in enumerate(orbits) if solver.Value(b[i]) for y in O)
    return "SAT", A, B, k


def check_graph(n, A, B):
    """Largest common-neighbour count of an edge and common-non-neighbour count of a non-edge."""
    v = 2 * n - 1
    A, B = set(A), set(B)
    C = set(range(1, v)) - A
    N = 2 * v
    rows = []
    for p in range(N):
        x, i = p % v, p // v
        r = 0
        for q in range(N):
            y, j = q % v, q // v
            if i == j:
                e = p != q and (y - x) % v in (A if i == 0 else C)
            else:
                e = ((y - x) if i == 0 else (x - y)) % v in B
            r |= int(e) << q
        rows.append(r)
    full = (1 << N) - 1
    cn = cnn = 0
    for p in range(N):
        for q in range(p + 1, N):
            if (rows[p] >> q) & 1:
                cn = max(cn, bin(rows[p] & rows[q]).count("1"))
            else:
                cnn = max(cnn, bin(full & ~rows[p] & ~rows[q] & ~(1 << p) & ~(1 << q)).count("1"))
    return cn, cnn


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("n", nargs="?", type=int, default=67)
    ap.add_argument("gens", nargs="*", type=int)
    ap.add_argument("--time", type=float, default=60.0)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out")
    o = ap.parse_args()
    n, v = o.n, 2 * o.n - 1
    H = subgroup(v, o.gens) if o.gens else [u for u in range(1, v) if pow(u, 3, v) == 1]
    st, A, B, k = search(n, H, o.time, o.workers, o.seed)
    print(f"n = {n}, v = {v}, |H| = {len(H)}, {k} H-orbits on Z_{v}: {st}")
    if st != "SAT":
        return 1
    cn, cnn = check_graph(n, A, B)
    good = cn <= n - 2 and cnn <= n - 1
    print(f"A = {A}\nB = {B}")
    print(f"check: edges have <= {cn} common neighbours (bound {n-2}), non-edges <= {cnn} common non-neighbours (bound {n-1}): {'ok' if good else 'FAIL'}")
    if o.out:
        json.dump({"n": n, "v": v, "H": H, "A": A, "B": B}, open(o.out, "w"))
    return 0 if good else 1


if __name__ == "__main__":
    sys.exit(main())
